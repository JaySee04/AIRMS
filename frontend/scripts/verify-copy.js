// WOULD A CLINICIAN WHO HAS NEVER SEEN THIS UNDERSTAND WHAT EACH THING DOES?
//
//   cd frontend; npm run verify:copy          # needs `npm run dev`
//
// Writes the ACTUAL RENDERED TEXT of every authenticated page to
// scripts/copy-dump.md (gitignored) so it can be read as prose, and reports the
// comprehension risks that can be detected mechanically.
//
// WHY A TOOL AND NOT A GREP (2026-10-09, §161). The first attempt at this
// audit grepped the source and was worthless: `cohort` matched 443 times, almost
// all of them variable names, and "cards with no subtitle" came back wrong
// because the prop sits several lines from the title. SOURCE IS NOT COPY. The
// only honest way to ask "is this understandable" is to read what a browser
// actually paints.
//
// WHAT IT CAN AND CANNOT DO, stated because the gap matters. It cannot tell you
// whether a sentence is CLEAR — that is a human reading the dump. It can tell
// you where to look: a number with no unit, an unexplained term, a card with no
// label line, an abbreviation that never gets expanded. It finds CANDIDATES.
// The dump is the deliverable; the findings are the index into it.
const fs = require('fs');
const path = require('path');
const puppeteer = require('puppeteer-core');

const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const WEB = process.env.E2E_WEB || 'http://localhost:3000';
const API = process.env.E2E_API || 'http://localhost:5000/api';
const OUT = path.join(__dirname, 'copy-dump.md');
const PW = 'airms2026';

// One athlete with a full record, so detail pages render something to read.
const ATH = process.env.ATH || '030109371036';

const PAGES = [
  // Kept in step with src/app by hand. It named /admin/analytics, /admin/athletes
  // and /medical/watchlist, none of which exist, and missed five real pages; the
  // dead routes reported "not measured" (rule 2 held), the missing ones nothing.
  ['admin', 'admin@isn.gov.my', ['/admin/dashboard', '/admin/activity', '/admin/reports',
    '/admin/audit', '/admin/personnel', '/admin/thresholds', '/admin/settings',
    '/admin/data-upload', '/admin/profile']],
  ['medical', 'medical@isn.gov.my', [`/medical/dashboard?athlete=${ATH}`, '/medical/sport-assessment',
    '/medical/profile']],
  ['coach', 'coach@isn.gov.my', ['/coach/dashboard', '/coach/reports', '/coach/profile']],
  ['athlete', 'athlete@isn.gov.my', ['/athlete/dashboard', '/athlete/history', '/athlete/squad',
    '/athlete/profile']],
  ['executive', 'executive@isn.gov.my', ['/admin/dashboard', '/admin/activity', '/admin/reports',
    '/admin/audit']],
];

// Terms a first-time clinician or coach may not share with us. Checked against
// RENDERED TEXT only, and only flagged when the page does not also explain them.
const JARGON = [
  ['MDC95', /\bMDC\s?95\b/i, /detectable change|smallest .*change/i],
  ['z-score', /\bz[-\s]?scores?\b/i, /standard deviation|how far .*from the (group|mean)/i],
  ['percentile', /\bpercentile\b/i, /out of \d+|better than|rank/i],
  ['cohort', /\bcohort\b/i, /peer group|athletes like|same sport|comparison group/i],
  ['typical error', /\btypical error\b/i, /measurement|noise|repeat/i],
  ['ACWR', /\bACWR\b/i, /acute.{0,4}chronic/i],
  ['myodynamia', /\bmyodynamia\b/i, /weak|deficien/i],
  ['PELAPIS/PODIUM', /\b(PELAPIS|PODIUM)\b/, /programme|tier|level/i],
  ['IQR', /\bIQR\b/, /interquartile|middle half/i],
];

async function login(email) {
  const r = await fetch(`${API}/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email, password: PW }),
  });
  if (!r.ok) throw new Error(`login failed for ${email} (${r.status})`);
  return r.json();
}

(async () => {
  const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox'] });
  const out = ['# SPIRiT — rendered copy, every authenticated page',
    '', 'GENERATED by `npm run verify:copy`. Read it as a first-time clinician would.',
    'This is what the browser actually paints, not what the source says.', ''];
  const findings = [];
  let visited = 0;

  for (const [role, email, routes] of PAGES) {
    const { token, user } = await login(email);
    const ctx = await browser.createBrowserContext();
    const page = await ctx.newPage();
    await page.setViewport({ width: 1440, height: 1100 });
    await page.goto(WEB, { waitUntil: 'domcontentloaded' });
    await page.evaluate((t, u) => {
      localStorage.setItem('airms_token', t);
      localStorage.setItem('airms_user', JSON.stringify(u));
      localStorage.setItem('airms_last_active', String(Date.now()));
    }, token, user);

    for (const route of routes) {
      await page.goto(`${WEB}${route}`, { waitUntil: 'networkidle2' });
      await new Promise((r) => { setTimeout(r, Number(process.env.SETTLE || 2500)); });
      await page.evaluate(() => {
        const b = [...document.querySelectorAll('button')].find((x) => /got it/i.test(x.textContent || ''));
        if (b) b.click();
      });
      await new Promise((r) => { setTimeout(r, 400); });

      const data = await page.evaluate(() => {
        const landed = location.pathname;
        const main = document.querySelector('main') || document.body;
        // Card headings paired with their label line — the §131 contract.
        const cards = [...document.querySelectorAll('.card-title')].map((h) => {
          const head = h.closest('.card-header') || h.parentElement;
          const sub = head?.querySelector('.card-sub');
          const tip = head?.querySelector('[data-infotip], .infotip, button[aria-expanded]');
          return { title: h.textContent.trim(), sub: sub?.textContent.trim() || '', tip: !!tip };
        });
        const text = main.innerText.replace(/\n{3,}/g, '\n\n').trim();
        return { landed, cards, text };
      });

      // Rule 2: a page that did not load must not read as a page with no problems.
      if (!data.landed.startsWith(route.split('?')[0])) {
        findings.push(`${role} ${route}: BOUNCED to ${data.landed} — not measured`);
        continue;
      }
      if (data.text.length < 200) {
        findings.push(`${role} ${route}: only ${data.text.length} chars rendered — not measured`);
        continue;
      }
      visited += 1;

      for (const c of data.cards) {
        if (!c.sub) findings.push(`${role} ${route}: card "${c.title}" has NO label line (§131)`);
      }
      for (const [name, hit, explained] of JARGON) {
        if (hit.test(data.text) && !explained.test(data.text)) {
          findings.push(`${role} ${route}: uses "${name}" with nothing on the page explaining it`);
        }
      }

      out.push(`\n---\n\n## ${role} · ${route}\n`);
      for (const c of data.cards) {
        out.push(`- **${c.title}** — ${c.sub || '_(no label line)_'}${c.tip ? ' · has info tip' : ''}`);
      }
      out.push('\n<details><summary>full rendered text</summary>\n\n```\n' + data.text + '\n```\n</details>\n');
    }
    await ctx.close();
  }
  await browser.close();

  fs.writeFileSync(OUT, out.join('\n'));
  const uniq = [...new Set(findings)];
  console.log(`\n  ${visited} page-visits read · dump: ${OUT}\n`);
  if (!uniq.length) {
    console.log('  no mechanical findings. THAT IS NOT A PASS — read the dump.\n');
  } else {
    for (const f of uniq) console.log(`  - ${f}`);
    console.log(`\n  ${uniq.length} candidate(s). Each is a PLACE TO LOOK, not a verdict.\n`);
  }
  // Never fails the build: this reports candidates for a human, and an exit 1
  // on "a card has no subtitle" would turn a reading aid into a gate.
  if (visited < 10) { console.error('  too few pages measured — check `npm run dev` is up.'); process.exit(2); }
})().catch((e) => { console.error('FAILED:', e.message); process.exit(2); });
