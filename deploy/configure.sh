#!/bin/sh
# Produce a READY-TO-COPY install bundle for an ISN server.
#
#   sh deploy/configure.sh --web airms.isn.gov.my --api airms-api.isn.gov.my
#
# Runs on JC's laptop (Git Bash) or on the server. Writes everything into
# deploy/out/, which is GITIGNORED because it contains generated secrets.
#
# WHY THIS EXISTS (2026-10-09, §160). The previous answer to "where do I do
# this" was a list of files to hand-edit — two hostnames in four places, a
# password placeholder, a secret to paste. Every one of those is a chance to
# miss a spot, and the failure mode of missing one is not an error: nginx serves
# the wrong vhost, or the API talks to a database it cannot reach, and you debug
# it on install day with a clinician waiting.
#
# Generating the bundle also means the SECRETS ARE MADE PROPERLY. A human asked
# for "a long random string" at 9am on install day types something memorable.
#
# IDEMPOTENT WITH ONE EXCEPTION: it will not overwrite an existing secret. Run
# it twice and the JWT secret is stable, because regenerating it silently
# invalidates every session and every outstanding invitation code.

set -eu

WEB_HOST=""
API_HOST=""
APP_DIR="/opt/airms"
DB_NAME="airms"
DB_USER="airms"

while [ $# -gt 0 ]; do
  case "$1" in
    --web) WEB_HOST="$2"; shift 2 ;;
    --api) API_HOST="$2"; shift 2 ;;
    --app-dir) APP_DIR="$2"; shift 2 ;;
    --db-name) DB_NAME="$2"; shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/out"

if [ -z "$WEB_HOST" ] || [ -z "$API_HOST" ]; then
  cat >&2 <<USAGE
usage: sh deploy/configure.sh --web <web-hostname> --api <api-hostname>

  --web       browser-facing hostname for the web app
  --api       browser-facing hostname for the API  (MUST be a different name —
              NEXT_PUBLIC_API_URL is baked in at build time and the backend's
              CORS allow-list is a separate origin)
  --app-dir   where AIRMS will live on the server   (default /opt/airms)
  --db-name   MySQL schema name                     (default airms)

Do not know the hostnames yet? Ask ISN for them before running this — they are
baked into the frontend build and into the TLS certificates, and changing them
later means a rebuild, not a config edit.
USAGE
  exit 2
fi

mkdir -p "$OUT"

# --- secrets --------------------------------------------------------------
# Kept across runs. Regenerating JWT_SECRET signs everyone out and invalidates
# every outstanding activation code; regenerating the DB password desynchronises
# api.env from the GRANT already applied.
SECRETS="$OUT/.secrets"
if [ -f "$SECRETS" ]; then
  # shellcheck disable=SC1090
  . "$SECRETS"
  echo "  reusing existing secrets ($SECRETS)"
else
  if command -v openssl >/dev/null 2>&1; then
    JWT_SECRET="$(openssl rand -base64 48 | tr -d '\n')"
    DB_PASSWORD="$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | cut -c1-28)"
  else
    echo "openssl not found — cannot generate secrets safely" >&2
    exit 2
  fi
  printf "JWT_SECRET='%s'\nDB_PASSWORD='%s'\n" "$JWT_SECRET" "$DB_PASSWORD" > "$SECRETS"
  chmod 600 "$SECRETS"
  echo "  generated new secrets ($SECRETS — chmod 600, gitignored)"
fi

# --- /etc/airms/api.env ----------------------------------------------------
cat > "$OUT/api.env" <<EOF
# AIRMS API — /etc/airms/api.env
# GENERATED by deploy/configure.sh. Contains secrets: root:airms, mode 640.
#   sudo install -d -m 750 /etc/airms
#   sudo install -o root -g airms -m 640 api.env /etc/airms/api.env

NODE_ENV=production
PORT=5000

# The backend's CORS allow-list. Must be the BROWSER-FACING web origin.
FRONTEND_URL=https://$WEB_HOST

JWT_SECRET=$JWT_SECRET
JWT_EXPIRES_IN=7d

MYSQL_HOST=localhost
MYSQL_PORT=3306
MYSQL_DATABASE=$DB_NAME
MYSQL_USER=$DB_USER
MYSQL_PASSWORD=$DB_PASSWORD

# Scheduled mail is driven by airms-mail.timer, so the in-process ticker is off.
# Leaving both on is safe (the sends take a cross-process lock) but muddy.
MAIL_SCHEDULER=off

# ---------------------------------------------------------------------------
# SMTP — THE ONE BLOCK ONLY ISN CAN FILL. Until these are set, mail is PRINTED
# TO THE SERVER LOG and never sent, which means invitations never arrive and
# nobody but the bootstrap admin can get an account.
# All four move TOGETHER: a provider only sends as the account it authenticated,
# so an isn.gov.my SMTP_FROM on someone else's transport is silently rewritten.
# ---------------------------------------------------------------------------
SMTP_HOST=
SMTP_PORT=587
SMTP_SECURE=false
SMTP_USER=
SMTP_PASS=
SMTP_FROM=AIRMS <injriskdashboard@isn.gov.my>

# Vision provider. OPTIONAL: expanded HoloMotion reports are read from the text
# layer and cost nothing. Needed ONLY for the compact 12-page layout.
VISION_PROVIDER=openai
VISION_API_KEY=
VISION_BASE_URL=
VISION_MODEL=

# Largest upload the API accepts. MUST match client_max_body_size in the nginx
# config — a mismatch fails as an opaque 413 at the proxy, before any AIRMS code
# runs and before any AIRMS log sees it.
AIRMS_MAX_UPLOAD_BYTES=20971520

# Per-user hourly cap on provider calls. Raise for bulk onboarding.
AIRMS_VISION_HOURLY_CAP=60

# Backups
AIRMS_BACKUP_DIR=/var/backups/$DB_NAME
AIRMS_BACKUP_KEEP_DAYS=30
EOF
chmod 600 "$OUT/api.env"

# --- /etc/airms/web.env ----------------------------------------------------
cat > "$OUT/web.env" <<EOF
# AIRMS web — /etc/airms/web.env
# GENERATED by deploy/configure.sh.
#
# NEXT_PUBLIC_API_URL IS BAKED IN AT BUILD TIME. It is listed here for the
# record; changing it means rebuilding the frontend, not restarting it. If the
# API hostname ever changes, rebuild — the symptom otherwise is every panel
# rendering empty, which looks exactly like a CORS failure and is not one.
NODE_ENV=production
PORT=3000
NEXT_PUBLIC_API_URL=https://$API_HOST/api
EOF

# --- frontend build env ----------------------------------------------------
cat > "$OUT/frontend.env.production" <<EOF
# Copy to frontend/.env.production BEFORE running \`npm run build\`.
NEXT_PUBLIC_API_URL=https://$API_HOST/api
EOF

# --- nginx -----------------------------------------------------------------
sed -e "s/airms-api\.isn\.gov\.my/$API_HOST/g" \
    -e "s/airms\.isn\.gov\.my/$WEB_HOST/g" \
    "$HERE/nginx-airms.conf" > "$OUT/nginx-airms.conf"

# --- database user ---------------------------------------------------------
sed -e "s/CHANGE-ME-BEFORE-RUNNING/$DB_PASSWORD/" \
    -e "s/\`airms\`/\`$DB_NAME\`/g" \
    "$HERE/airms-db-user.sql" > "$OUT/airms-db-user.sql"
chmod 600 "$OUT/airms-db-user.sql"

# --- systemd ---------------------------------------------------------------
for u in airms-api.service airms-web.service airms-mail.service airms-mail.timer \
         airms-backup.service airms-backup.timer; do
  sed -e "s#/opt/airms#$APP_DIR#g" "$HERE/$u" > "$OUT/$u"
done
cp "$HERE/airms-backup.sh" "$OUT/airms-backup.sh"

# --- the runbook, with the real values in it -------------------------------
cat > "$OUT/INSTALL.md" <<EOF
# AIRMS install — $WEB_HOST

Generated by \`deploy/configure.sh\`. **This directory contains secrets** — it is
gitignored; copy it to the server over ssh/scp, do not email it.

| | |
|---|---|
| Web | https://$WEB_HOST |
| API | https://$API_HOST |
| App directory | $APP_DIR |
| Database | \`$DB_NAME\` as \`$DB_USER\`@localhost |

## 1. Copy across
\`\`\`sh
scp -r deploy/out youruser@$WEB_HOST:/tmp/airms-install
ssh youruser@$WEB_HOST
\`\`\`

## 2. User, directories, code
\`\`\`sh
sudo useradd --system --home $APP_DIR --shell /usr/sbin/nologin airms || true
sudo install -d -o airms -g airms $APP_DIR /var/lib/airms /var/backups/$DB_NAME
sudo install -d -m 750 /etc/airms
# copy the repository to $APP_DIR, then:
cd $APP_DIR && npm run install:all
\`\`\`

## 3. Configuration
\`\`\`sh
cd /tmp/airms-install
sudo install -o root -g airms -m 640 api.env /etc/airms/api.env
sudo install -o root -g airms -m 640 web.env /etc/airms/web.env
sudo cp frontend.env.production $APP_DIR/frontend/.env.production
\`\`\`

## 4. Database
\`\`\`sh
sudo mysql -e "CREATE DATABASE IF NOT EXISTS \\\`$DB_NAME\\\` CHARACTER SET utf8mb4;"
sudo mysql < airms-db-user.sql        # password already filled in
\`\`\`

## 5. Build
\`\`\`sh
cd $APP_DIR/frontend && npm run build
\`\`\`

## 6. Services
\`\`\`sh
sudo cp airms-backup.sh /usr/local/bin/airms-backup && sudo chmod 755 /usr/local/bin/airms-backup
sudo cp airms-*.service airms-*.timer /etc/systemd/system/
sudo systemctl daemon-reload
sudo systemctl enable --now airms-api airms-web airms-mail.timer airms-backup.timer
\`\`\`

## 7. TLS
\`\`\`sh
sudo cp nginx-airms.conf /etc/nginx/sites-available/airms
sudo ln -sf /etc/nginx/sites-available/airms /etc/nginx/sites-enabled/airms
sudo certbot --nginx -d $WEB_HOST -d $API_HOST
sudo nginx -t && sudo systemctl reload nginx
\`\`\`

## 8. Check, then create the first administrator
\`\`\`sh
cd $APP_DIR/backend
npm run verify:install        # exits 1 while anything is still a blocker
npm run verify:schema         # does the database match the models
npm run bootstrap:admin -- --email "drthung@isn.gov.my" --name "Dr Thung"
\`\`\`
\`bootstrap:admin\` prints a one-time activation code. **It sets no password** —
whoever runs it cannot sign in as the administrator they created. Hand the code
to Dr Thung; he sets the first real credential at \`https://$WEB_HOST/activate\`.

**DO NOT run \`npm run seed\`.** It drops every table and inserts ~60 fabricated
athletes. It refuses against a production-looking database, but do not test that.

## Still outstanding
- **SMTP is blank** in api.env. Until ISN provides a relay, mail is printed to
  the server log and no invitation reaches anyone. \`verify:install\` reports it
  as a blocker.
- The TLS certificates, from certbot or ISN's own CA.
EOF

echo
echo "  bundle ready: $OUT"
echo "    api.env, web.env, frontend.env.production"
echo "    nginx-airms.conf      ($WEB_HOST, $API_HOST)"
echo "    airms-db-user.sql     (password filled in)"
echo "    6 systemd units       (app dir $APP_DIR)"
echo "    INSTALL.md            (the runbook, with your values in it)"
echo
echo "  SECRETS ARE IN THERE. Gitignored; copy over ssh, never email."
echo "  Still blank and only ISN can fill it: the SMTP block in api.env."
echo
